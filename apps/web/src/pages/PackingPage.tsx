function channelLabel(code: string | null | undefined): string {
  const normalized = (code ?? '').toLowerCase();
  if (normalized === 'digikala') return 'دیجی‌کالا';
  if (normalized === 'carexy') return 'کرکسی';
  return code ?? 'بدون کانال';
}

function channelTone(code: string | null | undefined): BadgeTone {
  const normalized = (code ?? '').toLowerCase();
  if (normalized === 'digikala') return 'danger';
  if (normalized === 'carexy') return 'info';
  return 'neutral';
}

function packStatusBadge(status: string) {
  const meta = PACK_STATUS[status] ?? { label: status, tone: 'neutral' as const };
  return <Badge tone={meta.tone}>{meta.label}</Badge>;
}

function ageLabel(minutes: number): string {
  if (!Number.isFinite(minutes) || minutes <= 0) return 'همین حالا';
  if (minutes < 60) return `${formatNumber(minutes)} دقیقه`;
  const hours = Math.floor(minutes / 60);
  if (hours < 24) return `${formatNumber(hours)} ساعت`;
  return `${formatNumber(Math.floor(hours / 24))} روز`;
}

/** Reads the first non-empty string of a shipping address under any known key. */
function addressField(address: PackShippingAddress | null, keys: readonly string[]): string | null {
  if (address === null) return null;
  for (const key of keys) {
    const value = address[key];
    if (typeof value === 'string' && value.trim().length > 0) return value.trim();
  }
  return null;
}

/** One printable address line assembled from the structured shipping address. */
function addressText(address: PackShippingAddress | null): string | null {
  if (address === null) return null;
  const parts: string[] = [];
  const line = addressField(address, ['line1', 'addressLine', 'address_line', 'address', 'line']);
  if (line !== null) parts.push(line);
  for (const key of ['district', 'city', 'province']) {
    const value = address[key];
    if (typeof value === 'string' && value.trim().length > 0) parts.push(value.trim());
  }
  const postal = addressField(address, ['postalCode', 'postal_code']);
  if (postal !== null) parts.push(`کد پستی ${postal}`);
  return parts.length > 0 ? parts.join('، ') : null;
}

function itemQty(item: PackTaskItem): string {
  return item.qty;
}

function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

/**
 * Prints the address label generated by Carexy/ERP. The label block carries the
 * order number (plus package number, recipient, phone and address) and is the
 * only thing on the printed page — Digikala orders never call this.
 */
function printAddressLabel(label: PackAddressLabel): boolean {
  const printWindow = window.open('', '_blank', 'width=520,height=720');
  if (printWindow === null) return false;
  printWindow.opener = null;
  const rows = [
    `<div class="row"><span class="key">شماره سفارش</span><span class="value order">${escapeHtml(label.orderNo)}</span></div>`,
    label.packageNo === null
      ? ''
      : `<div class="row"><span class="key">شماره بسته</span><span class="value">${escapeHtml(label.packageNo)}</span></div>`,
    label.recipient === null
      ? ''
      : `<div class="row"><span class="key">گیرنده</span><span class="value">${escapeHtml(label.recipient)}</span></div>`,
    label.phone === null
      ? ''
      : `<div class="row"><span class="key">تلفن</span><span class="value" dir="ltr">${escapeHtml(label.phone)}</span></div>`,
    label.address === null
      ? ''
      : `<div class="row"><span class="key">نشانی</span><span class="value">${escapeHtml(label.address)}</span></div>`,
  ].join('\n');
  printWindow.document.open();
  printWindow.document.write(`<!doctype html>
<html lang="fa" dir="rtl">
<head>
<meta charset="utf-8" />
<title>برچسب آدرس ${escapeHtml(label.orderNo)}</title>
<style>
  @page { size: A5; margin: 8mm; }
  * { box-sizing: border-box; }
  html, body { margin: 0; padding: 0; background: #ffffff; color: #000000; }
  body { font-family: Tahoma, 'Segoe UI', sans-serif; }
  .label { width: 100mm; min-height: 60mm; border: 2px solid #000; border-radius: 4mm; padding: 5mm; }
  .title { font-size: 12pt; font-weight: bold; text-align: center; border-bottom: 1px solid #000; padding-bottom: 2mm; margin-bottom: 3mm; }
  .row { display: flex; gap: 3mm; margin-bottom: 2mm; font-size: 10pt; }
  .key { min-width: 24mm; color: #333; }
  .value { flex: 1; }
  .order { font-size: 14pt; font-weight: bold; letter-spacing: 1px; }
  .toolbar { display: flex; justify-content: center; padding: 8mm 0; }
  .toolbar button { padding: 6px 24px; font: inherit; color: #fff; background: #1d4ed8; border: 0; border-radius: 6px; cursor: pointer; }
  @media print { .toolbar { display: none; } }
</style>
</head>
<body>
  <div class="label">
    <div class="title">برچسب ارسال سفارش</div>
    ${rows}
  </div>
  <div class="toolbar"><button type="button" onclick="window.print()">چاپ برچسب</button></div>
</body>
</html>`);
  printWindow.document.close();
  printWindow.focus();
  printWindow.print();
  return true;
}

/**
 * Explains exactly why the packing queue is empty: the `pack_tasks` migration
 * missing, no order fully picked yet, picked orders without a pack task, or
 * simply everything packed.
 */
function PackQueueEmptyState({ diagnostics }: { readonly diagnostics: PackBoardDiagnostics }) {
  if (diagnostics.tasksTotal === 0) {
    if (diagnostics.pickedTasks === 0 && diagnostics.pickedOrders === 0) {
      return (
        <EmptyState
          icon={<PackageCheck className="size-9" />}
          title="هنوز هیچ سفارشی کامل برداشت نشده است"
          description="تسک بسته‌بندی زمانی ساخته می‌شود که همهٔ قلم‌های یک سفارش در ایستگاه برداشت تکمیل شوند."
        />
      );
    }
    if (diagnostics.pickedOrdersWithoutPackTask > 0) {
      return (
        <EmptyState
          icon={<AlertTriangle className="size-9 text-amber-500" />}
          title={`${formatNumber(diagnostics.pickedOrdersWithoutPackTask)} سفارش برداشت‌شده تسک بسته‌بندی ندارد`}
          description="این سفارش‌ها وضعیت «برداشت‌شده» دارند اما ردیفی در pack_tasks ندارند؛ مهاجرت جدول بسته‌بندی یا رویداد تکمیل برداشت را بررسی کنید."
        />
      );
    }
    return (
      <EmptyState
        icon={<PackageCheck className="size-9" />}
        title="صف بسته‌بندی خالی است"
        description="پس از تکمیل برداشت سفارش، تسک بسته‌بندی به‌صورت خودکار در این صف ظاهر می‌شود."
      />
    );
  }
  return (
    <EmptyState
      icon={<CheckCircle2 className="size-9 text-emerald-500" />}
      title="همهٔ بسته‌ها آمادهٔ ارسال‌اند"
      description={`${formatNumber(diagnostics.packed)} بسته بسته‌بندی و سفارش‌ها برای ارسال علامت‌گذاری شده‌اند.`}
    />
  );
}

/** One order = one package: every line of the order is listed together. */
