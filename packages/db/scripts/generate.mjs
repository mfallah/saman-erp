for (const T of TABLES) {
  const table = T.name;
  const partitioned = PARTITIONED.has(table) || T.partition === 'created_at';
  const cols = [];
  const constraints = [];
  const specNames = new Set((T.cols || []).map((l) => l.trim().split(/\s+/)[0]));
  const addStd = (name, ddl) => { if (!specNames.has(name)) cols.push(ddl); };

  if (!T.noStd && !partitioned) {
    addStd('id', '"id" bigint GENERATED ALWAYS AS IDENTITY');
    addStd('public_id', '"public_id" uuid NOT NULL DEFAULT gen_random_uuid()');
    addStd('created_at', '"created_at" timestamptz NOT NULL DEFAULT now()');
    if (!T.append) {
      addStd('updated_at', '"updated_at" timestamptz NOT NULL DEFAULT now()');
      addStd('created_by', '"created_by" bigint');
      addStd('updated_by', '"updated_by" bigint');
      addStd('version', '"version" integer NOT NULL DEFAULT 1');
    } else {
      addStd('created_by', '"created_by" bigint');
    }
    constraints.push('CONSTRAINT "pk_' + table + '" PRIMARY KEY ("id")');
    constraints.push('CONSTRAINT "uq_' + table + '_public_id" UNIQUE ("public_id")');
  } else if (!T.noStd && partitioned) {
    cols.push(`"id" bigint NOT NULL DEFAULT nextval('erp.${table}_id_seq')`);
    cols.push('"public_id" uuid NOT NULL DEFAULT gen_random_uuid()');
    cols.push('"created_at" timestamptz NOT NULL DEFAULT now()');
    if (!T.append) {
      cols.push('"updated_at" timestamptz NOT NULL DEFAULT now()');
      cols.push('"version" integer NOT NULL DEFAULT 1');
    }
    addStd('created_by', '"created_by" bigint');
    constraints.push('CONSTRAINT "pk_' + table + '" PRIMARY KEY ("id","created_at")');
    constraints.push('CONSTRAINT "uq_' + table + '_public_id_created_at" UNIQUE ("public_id","created_at")');
    w(`CREATE SEQUENCE IF NOT EXISTS erp.${table}_id_seq AS bigint START 1 INCREMENT 1;`);
  }
  if (T.softDel) addStd('deleted_at', '"deleted_at" timestamptz');

  const pkCols = [];
  for (const line of T.cols) {
    const c = parseCol(line);
    if (c.pk) { pkCols.push(c.name); cols.push(`${ident(c.name)} ${c.rawType === 'textarr' ? 'text[]' : c.rawType === 'cidr' ? 'cidr[]' : c.type}${c.name === 'parent_table' ? '' : ''}`); }
    else cols.push(`${ident(c.name)} ${c.type}${c.nn ? ' NOT NULL' : ''}${c.def !== null ? ' DEFAULT ' + sqlDefault(c.def) : ''}`);
    if (c.uq) constraints.push(`CONSTRAINT "uq_${table}_${c.name}" UNIQUE (${ident(c.name)})`);
    if (c.fk) constraints.push(`CONSTRAINT "fk_${table}_${c.name}" FOREIGN KEY (${ident(c.name)}) REFERENCES erp."${c.fk}" (id) ON DELETE ${(c.pd || 'restrict').toUpperCase()}`);
  }
  // bare pk column in noStd tables
  for (const pk of pkCols) constraints.push(`CONSTRAINT "pk_${table}" PRIMARY KEY (${ident(pk)})`);

  const uqList = T.uq || [];
  for (const colsArr of uqList) {
    const optional = T.softDel ? ' WHERE deleted_at IS NULL' : '';
    constraints.push(`CONSTRAINT "uq_${table}_${colsArr.join('_')}" UNIQUE (${colsArr.map(ident).join(',')})`);
    if (optional) constraints.pop(); // temp: emitted as partial index below
    if (optional) {
      w(`-- partial unique (soft delete): ${colsArr.join(',')}`);
    }
  }
  const ckList = T.ck || [];
  for (const [name, expr] of ckList) constraints.push(`CONSTRAINT "ck_${table}_${name}" CHECK (${expr})`);

  const body = [...cols, ...constraints].map((l) => '  ' + l).join(',\n');
  const partitionClause = partitioned ? '\n) PARTITION BY RANGE ("created_at");' : '\n);';
  w(`-- ${T.doc}`);
  w(`CREATE TABLE IF NOT EXISTS erp.${ident(table)} (\n${body}${partitionClause}`);

  // partition default
  if (partitioned) {
    w(`CREATE TABLE IF NOT EXISTS erp.${table}_default PARTITION OF erp.${table} DEFAULT;`);
    w(`CREATE INDEX IF NOT EXISTS ix_${table}_created_at_brin ON erp.${table} USING brin ("created_at") WITH (pages_per_range = 32);`);
    // two upcoming month partitions (maintenance job keeps them ahead)
    for (const [y, m] of [[2026, 10], [2026, 11]]) {
      const name = `${table}_p${y}${String(m).padStart(2, '0')}`;
      const next = m === 12 ? `${y + 1}-01` : `${y}-${String(m + 1).padStart(2, '0')}`;
      w(`CREATE TABLE IF NOT EXISTS erp.${name} PARTITION OF erp.${table} FOR VALUES FROM ('${y}-${String(m).padStart(2, '0')}-01 00:00:00+00') TO ('${next}-01 00:00:00+00');`);
    }
  }

  // plain indexes
  for (const colsArr of T.ix || []) {
    w(`CREATE INDEX IF NOT EXISTS ix_${table}_${colsArr.join('_')} ON erp.${ident(table)} (${colsArr.map(ident).join(',')});`);
  }
  // soft-delete partial uniques
  if (T.softDel) {
    for (const colsArr of T.uq || []) {
      w(`CREATE UNIQUE INDEX IF NOT EXISTS uq_${table}_${colsArr.join('_')}_active ON erp.${ident(table)} (${colsArr.map(ident).join(',')}) WHERE deleted_at IS NULL;`);
    }
  }
  // triggers
  if (!T.append && !T.noStd) {
    w(`CREATE TRIGGER trg_${table}_updated_at BEFORE UPDATE ON erp.${ident(table)} FOR EACH ROW EXECUTE FUNCTION erp.set_updated_at();`);
    w(`CREATE TRIGGER trg_${table}_version BEFORE UPDATE ON erp.${ident(table)} FOR EACH ROW EXECUTE FUNCTION erp.bump_version();`);
  }
  w('');
  log(table);
}

