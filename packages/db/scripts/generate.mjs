/* ----------------------------- type mapping ----------------------------- */
const SQL_TYPE = (t) => {
  if (t === 'cidr[]' || t === 'text[]') return t;
  const m = /^([a-z]+)(?:\(([^)]*)\))?$/.exec(t);
  if (!m) throw new Error('bad type ' + t);
  const [, base, args] = m;
  switch (base) {
    case 'bigint':
    case 'int':
    case 'integer':
    case 'smallint':
    case 'text':
    case 'uuid':
    case 'timestamptz':
    case 'date':
    case 'boolean':
    case 'jsonb':
    case 'inet':
    case 'bytea':
      return base === 'int' ? 'integer' : base;
    case 'varchar':
      return `varchar(${args})`;
    case 'char':
      return `char(${args})`;
    case 'numeric':
      return `numeric(${args})`;
    case 'cidr':
      return `cidr[]`;
    case 'textarr':
      return `text[]`;
    default:
      throw new Error('unknown type ' + t);
  }
};
const ident = (s) => `"${s}"`;
const snakeCamel = (s) => s.replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());
const STD = ['id', 'public_id', 'created_at', 'updated_at', 'created_by', 'updated_by', 'version'];
const PARTITIONED = new Set(['audit_logs', 'inventory_transactions', 'outbox_events', 'api_request_logs', 'channel_api_calls']);

function parseCol(line) {
  const parts = line.trim().split(/\s+/);
  const name = parts[0];
  const type = parts[1];
  let nn = false, pk = false, uq = false, def = null, fk = null, pd = null;
  for (let i = 2; i < parts.length; i++) {
    const p = parts[i];
    if (p === 'nn') nn = true;
    else if (p === 'pk') pk = true;
    else if (p === 'uq') uq = true;
    else if (p.startsWith('fk:')) fk = p.slice(3);
    else if (p.startsWith('pd:')) pd = p.slice(3);
    else if (p.startsWith('def:')) def = p.slice(4);
    else throw new Error(`bad column token "${p}" in "${line}"`);
  }
  return { name, type: SQL_TYPE(type), rawType: type, nn, pk, uq, def, fk, pd };
}
const sqlDefault = (d) => {
  if (d === null) return null;
  if (d === 'now()' || d === 'gen_random_uuid()' || d === 'current_date' || d === 'true' || d === 'false') return d;
  if (/^\d+(\.\d+)?$/.test(d)) return d;
  return d; // already-quoted literal from spec
};

