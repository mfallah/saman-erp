w(`CREATE OR REPLACE FUNCTION erp.allocate_document_no(p_org_id bigint, p_document_type varchar, p_fiscal_year_id bigint)
RETURNS varchar LANGUAGE plpgsql AS $$
DECLARE v_next bigint; v_prefix varchar(20); v_padding smallint;
BEGIN
  UPDATE erp.numbering_sequences
     SET next_value = next_value + 1, last_allocated_at = now()
   WHERE organization_id = p_org_id
     AND document_type = p_document_type
     AND fiscal_year_id IS NOT DISTINCT FROM p_fiscal_year_id
  RETURNING next_value - 1, prefix, padding INTO v_next, v_prefix, v_padding;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'NUMBERING_SEQUENCE_MISSING: % / % / %', p_org_id, p_document_type, p_fiscal_year_id;
  END IF;
  RETURN v_prefix || '-' || to_char(now(), 'YYYY') || '-' || lpad(v_next::text, v_padding, '0');
END $$;`);

