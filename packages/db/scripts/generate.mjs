w(`CREATE OR REPLACE FUNCTION erp.assert_journal_entry_balance() RETURNS void LANGUAGE plpgsql AS $$
DECLARE v_l int; v_d bigint; v_c bigint; v_h record;
BEGIN
  SELECT total_debit_amount, total_credit_amount, status INTO v_h FROM erp.journal_entries WHERE id = NEW.id;
  SELECT count(*), coalesce(sum(debit_amount),0), coalesce(sum(credit_amount),0)
    INTO v_l, v_d, v_c FROM erp.journal_lines WHERE journal_entry_id = NEW.id;
  IF v_h.status = 'posted' THEN
    IF v_l < 2 THEN RAISE EXCEPTION 'JOURNAL_UNBALANCED: entry % has % lines', NEW.id, v_l; END IF;
    IF v_d <> v_c THEN RAISE EXCEPTION 'JOURNAL_UNBALANCED: entry % debit % <> credit %', NEW.id, v_d, v_c; END IF;
    IF v_d = 0 THEN RAISE EXCEPTION 'JOURNAL_UNBALANCED: entry % has zero total', NEW.id; END IF;
    IF v_d <> v_h.total_debit_amount OR v_c <> v_h.total_credit_amount THEN
      RAISE EXCEPTION 'JOURNAL_UNBALANCED: entry % header totals mismatch', NEW.id; END IF;
  END IF;
END $$;

CREATE OR REPLACE FUNCTION erp.assert_journal_lines_balance() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_entry bigint; v_status varchar(20); v_l int; v_d bigint; v_c bigint;
BEGIN
  v_entry := coalesce(NEW.journal_entry_id, OLD.journal_entry_id);
  SELECT status INTO v_status FROM erp.journal_entries WHERE id = v_entry;
  IF v_status = 'posted' THEN
    SELECT count(*), coalesce(sum(debit_amount),0), coalesce(sum(credit_amount),0)
      INTO v_l, v_d, v_c FROM erp.journal_lines WHERE journal_entry_id = v_entry;
    IF v_l < 2 OR v_d <> v_c OR v_d = 0 THEN
      RAISE EXCEPTION 'JOURNAL_UNBALANCED: entry % (% lines, debit %, credit %)', v_entry, v_l, v_d, v_c;
    END IF;
  END IF;
  RETURN NULL;
END $$;

CREATE CONSTRAINT TRIGGER trg_journal_entries_assert_balanced
  AFTER INSERT OR UPDATE ON erp.journal_entries
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION erp.assert_journal_entry_balance();
CREATE CONSTRAINT TRIGGER trg_journal_lines_assert_balanced
  AFTER INSERT OR UPDATE OR DELETE ON erp.journal_lines
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION erp.assert_journal_lines_balance();

CREATE OR REPLACE FUNCTION erp.derive_journal_period() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_period record;
BEGIN
  SELECT p.id, p.fiscal_year_id, p.status INTO v_period
    FROM erp.accounting_periods p
   WHERE NEW.entry_date BETWEEN p.start_date AND p.end_date
   ORDER BY p.period_no LIMIT 1;
  IF v_period.id IS NULL THEN RAISE EXCEPTION 'PERIOD_NOT_FOUND: no accounting period for %', NEW.entry_date; END IF;
  IF v_period.status IN ('closed','locked') THEN RAISE EXCEPTION 'PERIOD_CLOSED: % is closed', NEW.entry_date; END IF;
  NEW.period_id := v_period.id;
  NEW.fiscal_year_id := v_period.fiscal_year_id;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_journal_entries_derive_period BEFORE INSERT OR UPDATE OF entry_date ON erp.journal_entries
  FOR EACH ROW EXECUTE FUNCTION erp.derive_journal_period();
`);

