w(`CREATE OR REPLACE FUNCTION erp.chain_audit(p_batch integer DEFAULT 500)
RETURNS integer LANGUAGE plpgsql SECURITY DEFINER SET search_path = erp, pg_temp AS $$
DECLARE r record; v_head record; v_prev char(64); v_seq bigint; v_hash char(64); v_next_id bigint; n int := 0;
BEGIN
  SELECT * INTO v_head FROM erp.audit_chain_heads WHERE organization_id = 1 FOR UPDATE;
  IF NOT FOUND THEN
    INSERT INTO erp.audit_chain_heads(organization_id, last_row_hash) VALUES (1, encode(digest('genesis','sha256'),'hex'))
    RETURNING * INTO v_head;
  END IF;
  v_prev := v_head.last_row_hash; v_seq := coalesce(v_head.last_audit_id, 0);
  FOR r IN SELECT id, created_at FROM erp.audit_logs
            WHERE organization_id = 1 AND entry_hash IS NULL
            ORDER BY created_at, id LIMIT p_batch LOOP
    v_seq := v_seq + 1;
    v_hash := encode(digest(coalesce(v_prev,'') || '|' || r.id::text || '|' || r.created_at::text, 'sha256'),'hex');
    UPDATE erp.audit_logs SET prev_hash = v_prev, entry_hash = v_hash, hash_seq = v_seq WHERE id = r.id AND created_at = r.created_at;
    v_prev := v_hash; v_next_id := r.id; n := n + 1;
  END LOOP;
  IF n > 0 THEN
    UPDATE erp.audit_chain_heads SET last_audit_id = v_next_id, last_created_at = now(), last_row_hash = v_prev, updated_at = now() WHERE organization_id = 1;
  END IF;
  RETURN n;
END $$;
REVOKE ALL ON FUNCTION erp.chain_audit(integer) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION erp.chain_audit(integer) TO saman_worker;`);

